function stage1Base(
  temperature: number,
  latitude: number,
  hemisphere: Hemisphere,
  moisture = 7.4,
  pressure = 1012,
  hasTerrain = false,
  timeOfDay: 'day' | 'night' = 'day',
): BaseConditions {
  return {
    ...makeBase(temperature, latitude, hemisphere, moisture, pressure, hasTerrain, timeOfDay),
    advectAir: true,
    fixedSources: true,
    surface: true,
  };
}

function sourceEntity(
  type: WeatherEntity['type'],
  x: number,
  y: number,
  strength: number,
  id: string,
  note: string,
  radius?: number,
): WeatherEntity {
  return createEntity(type, x, y, strength, { id, note, locked: true, layer: 'low', radius });
}

function makeBase(
  temperature: number,
  latitude: number,
  hemisphere: Hemisphere,
  moisture = 7.4,
  pressure = 1012,
  hasTerrain = false,
  timeOfDay: 'day' | 'night' = 'day',
): BaseConditions {
  return { P: pressure, T: temperature, Q: moisture, latitude, hemisphere, hasTerrain, timeOfDay };
}

function entity(
  type: EntityType,
  x: number,
  y: number,
  strength: number,
  id: string,
  note: string,
): WeatherEntity {
  return createEntity(type, x, y, strength, {
    id,
    locked: true,
    note,
    layer: type === 'trough' || type === 'ridge' || type === 'jet' ? 'high' : type === 'inversion' ? 'mid' : 'low',
  });
}

