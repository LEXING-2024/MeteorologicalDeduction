export function getLevel(index: number): LevelDefinition {
  const safeIndex = Math.max(0, Math.min(LEVELS.length - 1, index));
  return LEVELS[safeIndex];
}

export function cloneLevel(level: LevelDefinition): LevelDefinition {
  return {
    ...level,
    base: { ...level.base },
    cities: level.cities.map((city) => ({ ...city })),
    initialEntities: level.initialEntities.map((item) => ({ ...item })),
    allowedCards: [...level.allowedCards],
    entityBudget: level.entityBudget,
    layers: level.layers ? [...level.layers] : undefined,
    target:
      level.target.kind === 'multi' ||
      level.target.kind === 'persistent' ||
      level.target.kind === 'persistentRain' ||
      level.target.kind === 'accumulatedRain' ||
      level.target.kind === 'window' ||
      level.target.kind === 'sequence'
        ? {
            ...level.target,
            conditions: level.target.conditions.map((condition) => ({ ...condition })),
          }
        : { ...level.target },
    guide: level.guide
      ? { ...level.guide, from: { ...level.guide.from }, to: { ...level.guide.to } }
      : undefined,
  };
}
